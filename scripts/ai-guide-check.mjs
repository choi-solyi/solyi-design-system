import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {JSDOM} from 'jsdom';
import {designGuide} from '../site/design-guide-data.js';
import {renderAiGuide} from '../site/ai-guide.js';
import {renderDesignGuide} from './build-design-guide.mjs';
import {componentReferences} from '../site/component-api-data.js';
const root=new URL('../',import.meta.url),read=file=>readFile(new URL(file,root),'utf8');
const source=await read('DESIGN.md');
assert.equal(designGuide.text,source);
assert.equal(designGuide.sha256,createHash('sha256').update(source).digest('hex'));
assert.equal(await read('docs/DESIGN.md'),source,'Download bytes use the canonical source');
assert.equal(await read('docs/design-guide-data.js'),await read('site/design-guide-data.js'));
assert.equal(designGuide.html,renderDesignGuide(source));
assert.ok(source.includes(designGuide.prompt));
assert.ok(!new JSDOM(renderDesignGuide('# <script>alert(1)</script>\n\n- `<img src=x onerror=alert(1)>`')).window.document.querySelector('script,img'),'Source markup is escaped before rendering');
const names=new Set(componentReferences.map(component=>component.name));
for(const match of source.matchAll(/\bS[A-Z][A-Za-z]+\b/g))assert.ok(names.has(match[0]),'Documented component exists: '+match[0]);
for(const api of ['createSolyiVuetify','applySolyiAppearance','sRules','serverError','errorMessages','resetValidation','cancelled'])assert.ok(source.includes(api));
const tokens=JSON.parse(await read('tokens.json'));
for(const token of ['font-sans','font-mono','radius-button','radius-control','radius-card','radius-floating','radius-panel'])assert.ok(Object.hasOwn(tokens.base,token));
const dom=new JSDOM(renderAiGuide({section:(id,title,description,body)=>`<section id="${id}"><h2>${title}</h2><p>${description}</p>${body}</section>`}));
const d=dom.window.document,buttons=d.querySelectorAll('button[data-copy]');
assert.equal(buttons.length,2);assert.equal(buttons[0].dataset.copy,source);assert.equal(buttons[1].dataset.copy,designGuide.prompt);
assert.equal(d.querySelector('a[download]').getAttribute('href'),'./DESIGN.md');
assert.equal(d.querySelector('a[download]').download,'DESIGN.md');
assert.ok(d.querySelector('details>summary'));assert.equal(d.querySelectorAll('article h3').length,1);assert.ok(d.querySelectorAll('article h4').length>=8);
assert.ok(d.querySelectorAll('pre[tabindex="0"]').length>=2);
dom.window.close();
console.log('PASS: canonical DESIGN.md matches rendered/raw/copy/download text, one extracted prompt, escaped Markdown, actual38-component names/token references and accessible native disclosure. Packed/installed bytes and browser rendering are separate gates.');
